import { cp, mkdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
export const projectRoot = resolve(scriptDirectory, "..");
export const defaultOutputDirectory = join(projectRoot, "dist-pages");
const subdivisionRoot = join(projectRoot, "games", "subdivision");

export function normalizeBackendUrl(value) {
  const candidate = String(value || "").trim();
  if (!candidate) throw new Error("PUBLIC_BACKEND_URL is required (for example https://orbit-ops.onrender.com).");
  let url;
  try {
    url = new URL(candidate);
  } catch {
    throw new Error("PUBLIC_BACKEND_URL must be a valid absolute URL.");
  }
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password || url.search || url.hash) {
    throw new Error("PUBLIC_BACKEND_URL must be a plain HTTP(S) origin without credentials, query, or fragment.");
  }
  if (url.pathname !== "/") throw new Error("PUBLIC_BACKEND_URL must not contain a path.");
  return url.origin;
}

export function subdivisionSocketUrl(backendUrl) {
  const url = new URL(normalizeBackendUrl(backendUrl));
  url.protocol = url.protocol === "https:" ? "wss:" : "ws:";
  url.pathname = "/tips/ws";
  return url.href;
}

export function prefixSubdivisionDocument(source, fileName) {
  let text = String(source);
  if (fileName === "maps.js") return text.replaceAll("/assets/", "/tips/assets/");
  if (!["index.html", "legal.html"].includes(fileName)) return text;
  for (const assetPath of [
    "/assets/",
    "/orbit-ops-subdivision-badge-simple.png",
    "/orbit-ops-subdivision-logo-simple.png",
    "/dust2-minimap.png",
    "/client-config.js",
    "/maps.js",
    "/core.js",
    "/sw.js"
  ]) {
    text = text.replaceAll(assetPath, `/tips${assetPath}`);
  }
  text = text.replaceAll("/legal", "/tips/legal");
  if (fileName === "legal.html") text = text.replaceAll('href="/"', 'href="/tips/"');
  return text;
}

export function orbitClientConfig(backendUrl) {
  return `// Generated by scripts/buildCloudflarePages.mjs.\n` +
    `window.ORBIT_OPS_CLIENT_CONFIG = Object.freeze({\n` +
    `  backendUrl: ${JSON.stringify(normalizeBackendUrl(backendUrl))},\n` +
    `  subdivisionUrl: "/tips/"\n` +
    `});\n`;
}

export function subdivisionClientConfig(backendUrl) {
  return `// Generated by scripts/buildCloudflarePages.mjs.\n` +
    `window.JIMS_CLIENT_CONFIG = Object.freeze({\n` +
    `  multiplayerUrl: ${JSON.stringify(subdivisionSocketUrl(backendUrl))},\n` +
    `  apiKey: "",\n` +
    `  serviceWorkerEnabled: true,\n` +
    `  orbitReturnUrl: "/"\n` +
    `});\n`;
}

