function assertSafeOutput(outputDirectory) {
  const output = resolve(outputDirectory);
  const relativePath = relative(projectRoot, output);
  if (!relativePath || relativePath.startsWith("..") || relativePath.includes(`${sep}..${sep}`)) {
    throw new Error("CLOUDFLARE_PAGES_OUTPUT must be a dedicated directory inside this repository.");
  }
  if (!relativePath.startsWith("dist-")) {
    throw new Error("CLOUDFLARE_PAGES_OUTPUT must use a dist-* directory so cleanup cannot target source files.");
  }
  return output;
}

async function copyTree(source, destination) {
  await cp(source, destination, {
    recursive: true,
    filter: (entry) => !entry.endsWith(`${sep}.DS_Store`)
  });
}

async function copySubdivision(stagingDirectory, backendUrl, buildId) {
  const destination = join(stagingDirectory, "tips");
  await mkdir(destination, { recursive: true });
  await copyTree(join(subdivisionRoot, "assets"), join(destination, "assets"));
  for (const fileName of [
    "orbit-ops-subdivision-badge-simple.png",
    "orbit-ops-subdivision-logo-simple.png",
    "dust2-minimap.png",
    "core.js"
  ]) {
    await cp(join(subdivisionRoot, fileName), join(destination, fileName));
  }
  for (const fileName of ["index.html", "legal.html", "maps.js"]) {
    const source = await readFile(join(subdivisionRoot, fileName), "utf8");
    await writeFile(join(destination, fileName), prefixSubdivisionDocument(source, fileName));
  }
  const worker = (await readFile(join(subdivisionRoot, "sw.js"), "utf8"))
    .replace("james-garden-care-assets-v1", `orbit-ops-subdivision-pages-assets-${buildId}`)
    .replace(
      "name.startsWith('jims-game-assets-') || name.startsWith('james-garden-care-assets-')",
      "name.startsWith('jims-game-assets-') || name.startsWith('james-garden-care-assets-') || name.startsWith('orbit-ops-subdivision-pages-assets-')"
    )
    .replace("url.pathname.startsWith('/assets/')", "url.pathname.startsWith('/tips/assets/')");
  await writeFile(join(destination, "sw.js"), worker);
  await writeFile(join(destination, "client-config.js"), subdivisionClientConfig(backendUrl));
}

export async function buildCloudflarePages({
  backendUrl = process.env.PUBLIC_BACKEND_URL,
  outputDirectory = process.env.CLOUDFLARE_PAGES_OUTPUT || defaultOutputDirectory,
  buildId = String(process.env.CF_PAGES_COMMIT_SHA || "local").slice(0, 16).replace(/[^a-z0-9_-]/giu, "") || "local"
} = {}) {
  const backend = normalizeBackendUrl(backendUrl);
  const output = assertSafeOutput(outputDirectory);
  const staging = `${output}.staging-${process.pid}`;
  await rm(staging, { recursive: true, force: true });
  await mkdir(staging, { recursive: true });
  try {
    await copyTree(join(projectRoot, "public"), staging);
    await mkdir(join(staging, "vendor", "phaser", "dist"), { recursive: true });
    await cp(join(projectRoot, "node_modules", "phaser", "dist", "phaser.min.js"), join(staging, "vendor", "phaser", "dist", "phaser.min.js"));
    await mkdir(join(staging, "socket.io"), { recursive: true });
    await cp(join(projectRoot, "node_modules", "socket.io", "client-dist", "socket.io.min.js"), join(staging, "socket.io", "socket.io.js"));
    await writeFile(join(staging, "client-config.js"), orbitClientConfig(backend));
    await copySubdivision(staging, backend, buildId);
    await writeFile(join(staging, "_headers"), cloudflareHeaders(backend));
    await writeFile(join(staging, "_redirects"), "/tips /tips/ 301\n/tips/legal /tips/legal.html 200\n");
    await rm(output, { recursive: true, force: true });
    await rename(staging, output);
  } catch (error) {
    await rm(staging, { recursive: true, force: true });
    throw error;
  }
  const details = await stat(output);
  if (!details.isDirectory()) throw new Error("Cloudflare output was not created as a directory.");
  return { backendUrl: backend, outputDirectory: output };
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : "";
if (import.meta.url === invokedPath) {
  buildCloudflarePages()
    .then(({ backendUrl, outputDirectory }) => {
      console.log(`Cloudflare Pages bundle ready: ${relative(projectRoot, outputDirectory)}`);
      console.log(`Public multiplayer backend: ${backendUrl}`);
    })
    .catch((error) => {
      console.error(`Cloudflare Pages build failed: ${error.message}`);
      process.exitCode = 1;
    });
}
